#!/usr/bin/env python3
"""Generate pixel-exact lossless WebP derivatives for the 32 native HD card PNGs."""
from __future__ import annotations
import argparse, io, json, sys, tempfile
from pathlib import Path
from PIL import Image, __version__ as PILLOW_VERSION, features

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "ui/cards-hd"
OUTPUT = ROOT / "ui/cards-hd-webp"
JS_MANIFEST = ROOT / "ui/card-webp-manifest.js"
EXPECTED = {
    *(f"PROJ_{n:02d}" for n in range(1, 26)),
    "ROLE_PROTECTOR", "ROLE_SABOTEUR", "GREENCOIN",
    *(f"BACK_{n:02d}" for n in range(1, 5)),
}
METADATA = ("icc_profile", "exif", "xmp")

def pixels(data):
    with Image.open(io.BytesIO(data)) as image:
        image.load()
        return image.size, image.convert("RGBA").tobytes()

def sources():
    found = {p.stem: p for p in SOURCE.glob("*.png")}
    if set(found) != EXPECTED:
        raise ValueError(f"HD inventory mismatch; missing={sorted(EXPECTED-set(found))}; unexpected={sorted(set(found)-EXPECTED)}")
    return dict(sorted(found.items()))

def encode(path):
    with Image.open(path) as source:
        if source.format != "PNG":
            raise ValueError(f"Expected PNG: {path}")
        source.load()
        rgba = source.convert("RGBA")
        metadata = {k: source.info[k] for k in METADATA if isinstance(source.info.get(k), bytes)}
        buffer = io.BytesIO()
        rgba.save(buffer, format="WEBP", lossless=True, quality=100, method=6, exact=True, **metadata)
        data = buffer.getvalue()
        size, decoded = pixels(data)
        if size != rgba.size or decoded != rgba.tobytes():
            raise ValueError(f"Lossless RGBA verification failed: {path}")
        return data, metadata, size

def js_manifest(available):
    payload = json.dumps(available, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return "/* Generated by scripts/generate-card-webp.py; do not edit. */\nwindow.GREEN_TRAP_WEBP_CARDS = Object.freeze(" + payload + ");\n"

def generate():
    if not features.check("webp"):
        raise RuntimeError("Pillow was built without WebP support")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    available, records = {}, {}
    source_total = webp_total = saved_total = 0
    for card_id, path in sources().items():
        original_size = path.stat().st_size
        data, metadata, dimensions = encode(path)
        smaller = len(data) < original_size
        target = OUTPUT / f"{card_id}.webp"
        if smaller:
            target.write_bytes(data)
            available[card_id] = f"/cards-hd-webp/{card_id}.webp"
            webp_total += len(data)
            saved_total += original_size - len(data)
        elif target.exists():
            target.unlink()
        source_total += original_size
        records[card_id] = {
            "source": f"ui/cards-hd/{card_id}.png",
            "sourceBytes": original_size,
            "webp": f"ui/cards-hd-webp/{card_id}.webp" if smaller else None,
            "webpBytes": len(data),
            "used": smaller,
            "savedBytes": original_size-len(data) if smaller else 0,
            "dimensions": list(dimensions),
            "preservedMetadata": sorted(metadata),
            "pixelExact": True,
        }
        print(f"{'USE' if smaller else 'SKIP (not smaller)':18} {card_id:16} {original_size:>9,} -> {len(data):>9,} bytes")
    expected = {f"{key}.webp" for key in available}
    for stale in OUTPUT.glob("*.webp"):
        if stale.name not in expected:
            stale.unlink()
    manifest = {
        "format": "WebP lossless",
        "encoder": f"Pillow {PILLOW_VERSION}",
        "pixelVerification": "Decoded RGBA bytes compared exactly with source PNG",
        "assetCount": len(records), "webpCount": len(available),
        "sourceBytes": source_total, "webpBytes": webp_total,
        "savedBytes": saved_total, "assets": records,
    }
    (OUTPUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    JS_MANIFEST.write_text(js_manifest(available), encoding="utf-8")
    print(f"\n{len(available)}/{len(records)} smaller WebP files; saved {saved_total:,} bytes ({saved_total/source_total*100:.1f}%).")

def check():
    manifest_path = OUTPUT / "manifest.json"
    if not manifest_path.is_file() or not JS_MANIFEST.is_file():
        raise ValueError("Generated manifests are missing")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    found = sources()
    if manifest.get("assetCount") != len(found) or set(manifest.get("assets", {})) != set(found):
        raise ValueError("Manifest does not cover the complete PNG inventory")
    available, source_total, webp_total, saved_total = {}, 0, 0, 0
    for card_id, path in found.items():
        record = manifest["assets"][card_id]
        source_size = path.stat().st_size
        if record.get("sourceBytes") != source_size or record.get("pixelExact") is not True:
            raise ValueError(f"Stale/unverified manifest entry: {card_id}")
        source_total += source_size
        target = OUTPUT / f"{card_id}.webp"
        if record.get("used"):
            if not target.is_file():
                raise ValueError(f"Missing WebP: {card_id}")
            data = target.read_bytes()
            if len(data) >= source_size or len(data) != record.get("webpBytes"):
                raise ValueError(f"WebP is not smaller or manifest is stale: {card_id}")
            if pixels(path.read_bytes()) != pixels(data):
                raise ValueError(f"Decoded RGBA pixels differ: {card_id}")
            available[card_id] = f"/cards-hd-webp/{card_id}.webp"
            webp_total += len(data)
            saved_total += source_size-len(data)
        elif target.exists():
            raise ValueError(f"Unexpected WebP for non-smaller source: {card_id}")
    if JS_MANIFEST.read_text(encoding="utf-8") != js_manifest(available):
        raise ValueError("Browser manifest is stale")
    if (manifest.get("webpCount"), manifest.get("sourceBytes"), manifest.get("webpBytes"), manifest.get("savedBytes")) != (len(available), source_total, webp_total, saved_total):
        raise ValueError("Manifest totals are stale")
    print(f"Verified {len(available)}/{len(found)} lossless WebP files; saved {saved_total:,} bytes ({saved_total/source_total*100:.1f}%).")

def self_test():
    if not features.check("webp"):
        raise RuntimeError("Pillow was built without WebP support")
    with tempfile.TemporaryDirectory() as temp:
        path = Path(temp) / "test.png"
        image = Image.new("RGBA", (17, 13))
        px = image.load()
        for y in range(image.height):
            for x in range(image.width):
                px[x,y] = ((x*17)%256, (y*19)%256, (x*y*7)%256, (x*13+y*11)%256)
        px[0,0] = (255,17,93,0)
        image.save(path)
        encoded, _, _ = encode(path)
        if pixels(path.read_bytes()) != pixels(encoded):
            raise AssertionError("Synthetic RGBA self-test failed")
    print("Lossless WebP self-test passed, including RGB values under transparent pixels.")

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true")
    group.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    try:
        if args.self_test: self_test()
        elif args.check: check()
        else: generate()
    except Exception as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
